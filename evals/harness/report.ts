import { readFileSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { CaseResult } from '../scorers/case-assertions';
import type { Rate } from '../scorers/wilson';
import type { Gate, ResultsFile } from './run';

// The evaluation report (evaluation-plan §12, eval-framework "Final Evaluation Report"; TC-016). It is
// rendered from a results file ONLY: every number below is read from that file, nothing is recomputed
// from the dataset or re-run (CF-12). Rendering is pure, so the same file gives byte-identical Markdown.
//   tsx evals/harness/report.ts <results.json> [--out=<report.md>]

const pct = (x: number | null | undefined) => (x === null || x === undefined ? '—' : `${(x * 100).toFixed(1)} %`);
const interval = (r: Rate) => `${pct(r.wilson95.lower)}–${pct(r.wilson95.upper)}`;
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s: string) => `\`${s}\``;

function table(head: string[], rows: string[][]): string[] {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)];
}

function evidenceLines(c: CaseResult): string[] {
  if (!c.result) return [`  - ${c.error ? `${c.error.class}: ${c.error.message}` : c.notes.join('; ') || 'no verify() result'}`];
  return c.result.checks.map((ch) => `  - ${code(ch.id)} **${ch.status}**${ch.hardFail ? ' (hard fail)' : ''}: ${ch.evidence}`);
}

export function renderReportFromResults(r: ResultsFile, resultsPath: string): string {
  const p = r.provenance;
  const t = r.totals;
  const baseline = new Map((r.comparison.baseline?.gates ?? []).map((g) => [g.id, g.display]));
  const out: string[] = [];
  const h = (s: string) => out.push('', s, '');

  out.push(`# Udgam evaluation report — ${basename(resultsPath, '.json')}`);
  out.push('');
  out.push(
    `Generated by ${code('evals/harness/report.ts')} from ${code(basename(resultsPath))} only; do not edit by hand. ` +
      `Config ${code(p.config.mode)} (${p.config.version}), provider ${code(p.provider)}, commit ${code(p.git.shortSha)}${p.git.dirty ? ' (dirty tree)' : ''}, run ${p.timestampUtc}.`,
  );
  out.push('');
  out.push(`**Overall: ${r.summary.overall}**`);
  out.push('');
  out.push(`**Release recommendation:** ${r.summary.recommendation}`);

  h('## Critical blockers');
  if (r.summary.blockers.length === 0) out.push('None.');
  else out.push(...r.summary.blockers.map((b) => `- ${b}`));

  h('## Gates');
  const gateRow = (g: Gate) => [`${g.id} ${g.name}`, baseline.get(g.id) ?? '—', g.display, g.target, g.pass ? 'PASS' : 'FAIL'];
  out.push(...table(['Evaluation area', `Baseline${r.comparison.baseline ? ` (${r.comparison.baseline.name})` : ''}`, 'Current', 'Target', 'Result'], r.gates.map(gateRow)));
  out.push('');
  out.push('Category gates (evaluation-plan §6; reported, not owned by the harness exit code):');
  out.push('');
  out.push(...table(['Evaluation area', 'Baseline', 'Current', 'Target', 'Result'], r.categoryGates.map(gateRow)));

  h('## Case totals');
  out.push(...table(['Active', 'Passed', 'Failed', 'of which not yet implemented', 'Errored', 'Skipped'], [[t.active, t.passed, t.failed, t.notYetImplemented, t.errored, t.skipped].map(String)]));
  out.push('');
  out.push(
    `Active = cases in the ${p.suites.map(code).join(' and ')} suite(s) with status active or stretch. ` +
      '`not_yet_implemented` means a check or suite the case needs is not built yet; it counts as failed. ' +
      `Integrity: ${t.ok ? 'totals reconcile with the dataset' : `**failed** — ${t.problems.join('; ')}`}.`,
  );
  if (r.scope) {
    out.push('');
    out.push(
      `Milestone scope: ${code(r.scope.milestone)}. Gates and critical conditions count only cases of milestones up to ${r.scope.milestone}; ` +
        `${r.scope.outOfScope.length} case(s) of a later milestone are counted in the totals above and listed under "Out of milestone scope".`,
    );
  }

  h('## Detection (S1), scenarios 1–4');
  const d = r.detection;
  out.push(
    ...table(
      ['Scenario', 'Detected', 'Rate', 'Wilson 95 %'],
      [
        ...(['1', '2', '3', '4'] as const).map((s) => [s, `${d.perScenario[s].k}/${d.perScenario[s].n}`, pct(d.perScenario[s].rate), interval(d.perScenario[s])]),
        ['pooled', `${d.pooled.k}/${d.pooled.n}`, pct(d.pooled.rate), interval(d.pooled)],
      ],
    ),
  );
  out.push('');
  out.push('Detected = the verdict is acceptable **and** one of the case’s catching checks returned flag or fail (EV4).');
  out.push('');
  out.push('Scenarios 5–6 (stretch; reported, not in S1):');
  out.push('');
  out.push(...table(['Scenario', 'Detected', 'Rate', 'Wilson 95 %'], (['5', '6'] as const).map((s) => [s, `${d.otherScenarios[s].k}/${d.otherScenarios[s].n}`, pct(d.otherScenarios[s].rate), interval(d.otherScenarios[s])])));

  h('## False positives (S2)');
  const fp = r.falsePositives;
  out.push(`False-positive rate ${pct(fp.rate)} (${fp.k}/${fp.n}), Wilson 95 % ${interval(fp)}. Honest review load (legitimate + edge not Verified): ${pct(fp.honestReviewLoad.rate)} (${fp.honestReviewLoad.k}/${fp.honestReviewLoad.n}).`);
  out.push('');
  if (fp.fps.length === 0) out.push('No false positives.');
  else out.push(...table(['Case', 'Outcome', 'Verdict', 'Checks not ok'], fp.fps.map((x) => [x.id, x.outcome, x.verdict ?? '—', x.responsible.join(', ') || '—'])));

  if (r.scope && r.scope.outOfScope.length > 0) {
    h('## Out of milestone scope');
    out.push(`Run with ${code(`--milestone=${r.scope.milestone}`)}. These cases ran (or were recorded) like every other case, but belong to a later milestone: they are reported here and are not pooled into any ${r.scope.milestone} gate or critical condition.`);
    out.push('');
    out.push(...table(['Case', 'Suite', 'Milestone', 'Outcome', 'Notes'], r.scope.outOfScope.map((c) => [c.id, c.suite, c.milestone, c.outcome, c.notes.join('; ') || '—'])));
  }

  h('## Failed evaluation IDs');
  const failed = r.cases.filter((c) => c.outcome === 'failed');
  const nyi = r.cases.filter((c) => c.outcome === 'not_yet_implemented');
  const errored = r.cases.filter((c) => c.outcome === 'errored');
  out.push(`- **Failed (${failed.length}):** ${failed.map((c) => c.id).join(', ') || 'none'}`);
  const missing = (c: CaseResult) => (c.missingChecks.length === 0 ? '' : c.missingChecks.length > 3 ? ` (${c.missingChecks.length} checks)` : ` (${c.missingChecks.join(', ')})`);
  out.push(`- **Not yet implemented (${nyi.length}):** ${nyi.map((c) => `${c.id}${missing(c)}`).join(', ') || 'none'}`);
  out.push(`- **Errored (${errored.length}):** ${errored.map((c) => `${c.id} (${c.error?.class}: ${c.error?.message})`).join(', ') || 'none'}`);
  if (failed.length > 0) {
    out.push('');
    out.push('Failed assertions:');
    out.push('');
    for (const c of failed) for (const a of c.assertions.filter((x) => !x.pass)) out.push(`- ${c.id} ${code(a.name)}: ${a.detail}`);
  }

  h('## Undetected attacks, with evidence');
  if (d.undetected.length === 0) out.push('None.');
  for (const u of d.undetected) {
    const c = r.cases.find((x) => x.id === u.id)!;
    out.push(`- **${u.id}** (scenario ${u.scenario}, ${u.outcome}, verdict ${u.verdict ?? '—'})${u.missingChecks.length ? ` — needs ${u.missingChecks.join(', ')}` : ''}`);
    out.push(...evidenceLines(c));
  }

  h('## Known limitations');
  out.push('Attacks the MVP cannot catch by design (EV6). Recorded with their verdicts, never counted in S1.');
  out.push('');
  if (r.knownLimitations.length === 0) out.push('None in this run.');
  else out.push(...table(['Case', 'Scenario', 'Verdict', 'Why'], r.knownLimitations.map((k) => [k.id, String(k.scenario ?? '—'), k.verdict ?? '—', k.behavior ?? '—'])));

  h('## Paired cases (same signal, opposite ground truth)');
  if (r.pairs.length === 0) out.push('No pairs in this run.');
  for (const pair of r.pairs) {
    const [a, b] = pair.cases as [Pair0, Pair0];
    const checks = [...new Set([...Object.keys(a.checks), ...Object.keys(b.checks)])];
    out.push('');
    out.push(
      ...table(
        ['', a.id, b.id],
        [
          ['class', a.caseClass ?? '—', b.caseClass ?? '—'],
          ['outcome', a.outcome, b.outcome],
          ['verdict', a.verdict ?? '—', b.verdict ?? '—'],
          ['score', a.score === null ? '—' : String(a.score), b.score === null ? '—' : String(b.score)],
          ...checks.map((id) => [id, a.checks[id as keyof typeof a.checks] ?? '—', b.checks[id as keyof typeof b.checks] ?? '—']),
        ],
      ),
    );
  }

  h('## Critical conditions');
  if (r.criticalConditions.length === 0) out.push('None fired.');
  else out.push(...table(['CF', 'Cases', 'Reason'], r.criticalConditions.map((f) => [f.id, f.caseIds.join(', ') || '—', f.reason])));

  h('## Regressions and baseline');
  const cmp = r.comparison;
  out.push(`- Previous formal run: ${cmp.previous ? `${code(cmp.previous.file)} (${cmp.previous.timestampUtc})` : 'none'}`);
  out.push(`- Regressions (passed before, not now): ${cmp.regressions.join(', ') || 'none'}`);
  out.push(`- Improvements: ${cmp.improvements.join(', ') || 'none'}`);
  out.push(`- Baseline: ${cmp.baseline ? `${cmp.baseline.name} (${code(cmp.baseline.file)})` : 'none recorded yet'}`);

  const proofCases = r.cases.filter((c) => c.suite === 'harness-proof');
  // Only results written since the suite runs carry `proof`; older files (baseline-v0) render as they were.
  if (proofCases.some((c) => c.proof)) {
    h('## Proof suite (S6)');
    const library = (c: CaseResult): string => {
      const p = c.proof;
      if (!p) return '—';
      if (p.metrics) return `${p.metrics.verified}/${p.metrics.closureEntries} closure entries verified under ${p.metrics.checkpoints} checkpoints (coverage ${pct(p.metrics.coverage)})`;
      if (p.variants.length > 0) return p.variants.map((v) => `${v.variant}: ${v.lib.step ?? 'ACCEPTED'}`).join('; ');
      return c.assertions.map((a) => a.detail).join('; ') || '—';
    };
    const cleanRoom = (c: CaseResult): string => {
      const p = c.proof;
      if (!p) return '—';
      if (p.metrics && typeof p.metrics.cleanRoomVerified === 'number') return `${p.metrics.cleanRoomVerified}/${p.metrics.closureEntries} closure entries verified (coverage ${pct(p.metrics.cleanRoomCoverage)})`;
      if (p.variants.length > 0 && p.variants.every((v) => v.cleanRoom)) return p.variants.map((v) => `${v.variant}: ${v.cleanRoom.step ?? 'ACCEPTED'}`).join('; ');
      return p.cleanRoom.detail ?? p.cleanRoom.status;
    };
    out.push(...table(['Case', 'Outcome', 'Library verifier', 'Clean-room checker'], proofCases.map((c) => [c.id, c.outcome, library(c), cleanRoom(c)])));
    const score = proofCases.find((c) => c.proof?.score)?.proof?.score;
    if (score) {
      out.push('');
      out.push(
        `S6 score (evals/scorers/proof-verifier.ts): coverage library ${pct(score.coverage.lib)}, clean-room ${pct(score.coverage.cleanRoom)}; ` +
          `tampers rejected library ${pct(score.tamperRejected.lib)}, clean-room ${pct(score.tamperRejected.cleanRoom)} over ${score.perVariant.length} variants; ` +
          `variants accepted by either verifier: ${score.cf04.fired ? score.cf04.variants.join(', ') : 'none'} (run-level CF-04, which also covers a rejection at the wrong step, is under "Critical conditions").`,
      );
      out.push('');
      out.push(...table(['Variant', 'Expected step', 'Library', 'Clean-room', 'Steps match'], score.perVariant.map((v) => [v.variant, v.expectedStep, v.lib.step ?? 'ACCEPTED', v.cleanRoom.step ?? 'ACCEPTED', v.stepMatches ? 'yes' : 'NO'])));
    }
  }

  const noted = r.cases.filter((c) => c.notes.length > 0 && c.outcome !== 'not_yet_implemented');
  if (noted.length > 0) {
    h('## Case notes');
    for (const c of noted) out.push(`- ${c.id}: ${c.notes.join('; ')}`);
  }

  h('## Sample-size caveat');
  out.push(
    'With small seeded sets a perfect score does not prove a field detection rate. Each rate is shown with a Wilson 95 % interval: ' +
      'information, not a gate. For scale, 10/10 gives a lower bound of 72.2 %, 40/40 gives 91.2 % and 38/40 gives 83.5 %. ' +
      'The seeded set shows that each rule catches what it is meant to catch; it does not estimate how often fraud is caught in the field.',
  );
  if (p.yieldReference.placeholder) {
    out.push('');
    out.push(`Yield cases use the placeholder reference row (max ${p.yieldReference.row.maxKgHa} kg/ha, cherry-to-clean ${p.yieldReference.row.cherryToCleanRatio}); cases are written in multiples of U, so they stay valid when the Coffee Board row replaces it.`);
  }

  h('## Configuration');
  out.push(`${code(p.config.version)} · hash ${code(p.config.hash)} · mode ${code(p.config.mode)} · enabled checks: ${p.config.enabledChecks.join(', ')}`);
  out.push('');
  out.push(`Registry: ${p.registry.checks.join(', ') || 'none'}${p.registry.missing.length ? ` · not built yet: ${p.registry.missing.join(', ')}` : ''}`);
  out.push('');
  out.push('```json');
  out.push(JSON.stringify(p.config.object, null, 2));
  out.push('```');

  h('## Provenance');
  out.push(
    ...table(
      ['Field', 'Value'],
      [
        ['harness', `${p.harness.name} ${p.harness.version}`],
        ['app version', p.appVersion],
        ['commit', `${p.git.commit} (${p.git.branch}${p.git.dirty ? ', dirty' : ''})`],
        ['environment', p.environment],
        ['dataset', `${p.dataset.path} ${p.dataset.version} · sha256 ${p.dataset.sha256}`],
        ['fixtures', `${p.fixtures.version} · ${p.fixtures.files} files · sha256 ${p.fixtures.sha256}`],
        ['provider', p.provider],
        ['yield reference', `${p.yieldReference.version} · ${p.yieldReference.source}`],
        ['ledger', p.ledger],
        ['node', p.node],
        ['os / arch', `${p.os.platform} / ${p.os.arch}`],
        ['suites', p.suites.join(', ')],
        ['seed', String(p.seed)],
        ['timestamp (UTC)', p.timestampUtc],
        ['duration', `${p.durationMs} ms`],
      ],
    ),
  );
  out.push('');
  return out.join('\n');
}

type Pair0 = ResultsFile['pairs'][number]['cases'][number];

/** Render the report for a results file (reads only that file). */
export function renderReport(resultsPath: string): string {
  const r = JSON.parse(readFileSync(resultsPath, 'utf8')) as ResultsFile;
  return renderReportFromResults(r, resultsPath);
}

function main(argv: string[]): number {
  const file = argv.find((a) => !a.startsWith('--'));
  if (!file) {
    console.error('usage: tsx evals/harness/report.ts <results.json> [--out=<report.md>]');
    return 2;
  }
  const md = renderReport(resolve(file));
  const outArg = argv.find((a) => a.startsWith('--out='));
  if (outArg) writeFileSync(resolve(outArg.slice('--out='.length)), md);
  else process.stdout.write(md);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
